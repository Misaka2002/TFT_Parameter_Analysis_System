"""GitHub Dark 风格工作台布局；计算逻辑留在 ui/extraction 中。"""

from matplotlib.figure import Figure
from PySide6.QtCore import Qt, QSize
from PySide6.QtWidgets import (
    QAbstractItemView, QCheckBox, QComboBox, QDoubleSpinBox, QFormLayout, QFrame,
    QGridLayout, QHBoxLayout, QHeaderView, QLabel, QLineEdit, QPushButton, QScrollArea,
    QSizePolicy, QSplitter, QStackedWidget, QTableWidget, QTabWidget, QTextBrowser,
    QVBoxLayout, QWidget,
)

from .theme import icon
from .widgets import MetricCard, PlotToolbar
from .hover import CurveHoverController
from .canvas import StableFigureCanvas


def label(text, name="muted", wrap=False):
    widget = QLabel(text)
    widget.setObjectName(name)
    widget.setWordWrap(wrap)
    return widget


def button(text, glyph, callback, primary=False):
    widget = QPushButton(icon(glyph, "#ffffff" if primary else None), text)
    widget.setObjectName("primary" if primary else "secondary")
    widget.setIconSize(QSize(16, 16))
    widget.setCursor(Qt.CursorShape.PointingHandCursor)
    widget.clicked.connect(callback)
    return widget


def separator():
    line = QFrame()
    line.setFrameShape(QFrame.Shape.HLine)
    line.setObjectName("separator")
    line.setFixedHeight(1)
    return line


def section(layout, number, title, description=None):
    heading = QHBoxLayout()
    heading.setSpacing(8)
    heading.addWidget(label(number, "badge"))
    heading.addWidget(label(title, "sectionTitle"))
    heading.addStretch()
    layout.addLayout(heading)
    if description:
        layout.addWidget(label(description, "sectionDescription", True))


def combo():
    widget = QComboBox()
    widget.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    widget.setMinimumContentsLength(8)
    widget.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Fixed)
    return widget


def build_window(window):
    root = QWidget()
    root.setObjectName("appRoot")
    root_layout = QVBoxLayout(root)
    root_layout.setContentsMargins(0, 0, 0, 0)
    root_layout.setSpacing(0)

    header = QFrame()
    header.setObjectName("appHeader")
    header_layout = QHBoxLayout(header)
    header_layout.setContentsMargins(22, 16, 22, 16)
    brand = QLabel()
    brand.setPixmap(icon("chart", "#e6edf3", 28).pixmap(28, 28))
    header_layout.addWidget(brand)
    header_layout.addSpacing(8)
    header_layout.addWidget(label("TFT", "brandTitle"))
    header_layout.addWidget(label(" / ", "breadcrumb"))
    header_layout.addWidget(label("参数分析工作台", "brandTitle"))
    header_layout.addSpacing(10)
    header_layout.addWidget(label("本地运行", "badge"))
    header_layout.addStretch()
    header_layout.addWidget(button("使用说明", "help", window.show_help))
    root_layout.addWidget(header)

    command = QFrame()
    command.setObjectName("workspaceBar")
    commands = QHBoxLayout(command)
    commands.setContentsMargins(22, 12, 22, 12)
    commands.setSpacing(10)
    window.open_button = button("打开数据", "folder", window.open_file)
    commands.addWidget(window.open_button)
    commands.addSpacing(8)
    window.example_combo = combo()
    window.example_combo.addItems(["公开样本 1", "公开样本 2", "公开样本 3"])
    window.example_combo.setFixedWidth(120)
    commands.addWidget(window.example_combo)
    commands.addWidget(button("加载示例", "file", window.load_example))
    commands.addStretch()
    window.screenshot_button = button("保存截图", "camera", window.save_screenshot)
    window.export_button = button("导出分析结果", "download", window.save_results)
    window.export_button.setEnabled(False)
    commands.addWidget(window.screenshot_button)
    commands.addWidget(window.export_button)
    root_layout.addWidget(command)

    splitter = QSplitter(Qt.Orientation.Horizontal)
    splitter.setChildrenCollapsible(False)
    splitter.setHandleWidth(1)
    root_layout.addWidget(splitter, 1)
    window.workspace_splitter = splitter

    sidebar = QFrame()
    sidebar.setObjectName("settingsPanel")
    side = QVBoxLayout(sidebar)
    side.setContentsMargins(20, 20, 20, 20)
    side.setSpacing(12)
    section(side, "01", "数据与扫描段")
    window.file_label = label("尚未加载数据", "fileName", True)
    window.file_label.setMinimumWidth(0)
    window.file_label.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    window.file_label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    side.addWidget(window.file_label)
    window.sweep_combo = combo()
    window.sweep_combo.setPlaceholderText("加载数据后选择扫描段")
    window.sweep_combo.currentIndexChanged.connect(window.select_sweep)
    side.addWidget(window.sweep_combo)
    side.addSpacing(4)
    side.addWidget(separator())

    window.analysis_controls = QWidget()
    window.analysis_controls.setObjectName("analysisControls")
    analysis = QVBoxLayout(window.analysis_controls)
    analysis.setContentsMargins(0, 0, 0, 0)
    analysis.setSpacing(12)
    section(analysis, "02", "拟合设置", "选择拟合方法，并设置栅极电压范围。")
    analysis.addWidget(label("计算方法", "fieldLabel"))
    window.method = combo()
    window.method.addItem("饱和区：√Id–Vg 拟合", "saturation")
    window.method.addItem("线性区：Id–Vg 拟合", "linear")
    analysis.addWidget(window.method)
    range_grid = QGridLayout()
    range_grid.setHorizontalSpacing(10)
    range_grid.setVerticalSpacing(6)
    window.start, window.end = QDoubleSpinBox(), QDoubleSpinBox()
    for control in (window.start, window.end):
        control.setRange(-1e6, 1e6)
        control.setDecimals(6)
        control.setSingleStep(0.2)
        control.setSuffix(" V")
        control.setMinimumWidth(0)
        control.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Fixed)
        control.setKeyboardTracking(False)
    range_grid.addWidget(label("区间下限", "fieldLabel"), 0, 0)
    range_grid.addWidget(label("区间上限", "fieldLabel"), 0, 1)
    range_grid.addWidget(window.start, 1, 0)
    range_grid.addWidget(window.end, 1, 1)
    analysis.addLayout(range_grid)
    window.invert = QCheckBox("反转电流符号")
    window.invert.setToolTip("接线方向导致电流符号相反时，可勾选此项。导出时仍会保留原始电流。")
    window.confirm_region = QCheckBox("已核对工作区条件")
    window.confirm_region.setToolTip("请根据测量偏置和所选区间确认器件工作区，程序也会检查模型的近似条件。")
    analysis.addWidget(window.invert)
    analysis.addWidget(window.confirm_region)
    window.analyze_button = button("计算并更新结果", "chart", window.run_analysis, primary=True)
    window.analyze_button.setEnabled(False)
    analysis.addWidget(window.analyze_button)
    analysis.addWidget(label("请根据曲线调整拟合区间，并确认器件处于所选工作区。", "sectionDescription", True))
    analysis.addSpacing(6)
    analysis.addWidget(separator())
    section(analysis, "03", "器件参数", "不确定的参数可留空。计算迁移率时需要填写这些参数。")
    device_grid = QGridLayout()
    device_grid.setHorizontalSpacing(10)
    device_grid.setVerticalSpacing(6)
    window.width, window.length = QLineEdit(), QLineEdit()
    window.capacitance, window.drain = QLineEdit(), QLineEdit()
    fields = [("沟道宽 W / µm", window.width), ("沟道长 L / µm", window.length),
              ("Ci / nF·cm⁻²", window.capacitance), ("Vds / V", window.drain)]
    for index, (text, edit) in enumerate(fields):
        edit.setPlaceholderText("未知")
        edit.setMinimumWidth(0)
        edit.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Fixed)
        device_grid.addWidget(label(text, "fieldLabel"), (index // 2) * 2, index % 2)
        device_grid.addWidget(edit, (index // 2) * 2 + 1, index % 2)
    analysis.addLayout(device_grid)
    analysis.addWidget(label("Ci 表示单位面积栅电容。参数或工作区条件不满足时，不显示迁移率。", "sectionDescription", True))
    window.analysis_controls.setEnabled(False)
    side.addWidget(window.analysis_controls)
    side.addStretch()
    side.addSpacing(14)
    side.addWidget(label("适用于 n 型 TFT 的单段扫描\n可加载示例，也可导入数据", "sectionDescription", True))
    scroll = QScrollArea()
    scroll.setObjectName("settingsScroll")
    scroll.setWidgetResizable(True)
    scroll.setFrameShape(QFrame.Shape.NoFrame)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll.setWidget(sidebar)
    scroll.setMinimumWidth(290)
    scroll.setMaximumWidth(450)
    splitter.addWidget(scroll)

    workspace = QWidget()
    workspace.setObjectName("analysisWorkspace")
    content = QVBoxLayout(workspace)
    content.setContentsMargins(24, 20, 24, 18)
    content.setSpacing(14)
    title_row = QHBoxLayout()
    title_row.addWidget(label("转移特性分析", "pageTitle"))
    title_row.addStretch()
    window.state_badge = label("等待数据", "statusBadge")
    title_row.addWidget(window.state_badge)
    content.addLayout(title_row)
    window.source_badge = label("加载数据后，可以查看曲线、拟合结果和分析记录。", "muted")
    window.source_badge.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    content.addWidget(window.source_badge)
    metrics_layout = QHBoxLayout()
    metrics_layout.setSpacing(10)
    window.metrics = []
    for text, hint in [("阈值电压", "V，拟合估计值"), ("扫描电流比", "仅统计正电流"),
                       ("场效应迁移率", "cm²/(V·s)"), ("拟合 R²", "当前拟合区间")]:
        metric = MetricCard(text, hint)
        window.metrics.append(metric)
        metrics_layout.addWidget(metric, 1)
    content.addLayout(metrics_layout)
    window.result_note = label("加载数据并计算后，这里会显示分析结果。", "muted")
    window.result_note.setWordWrap(True)
    content.addWidget(window.result_note)

    window.content_stack = QStackedWidget()
    empty = QFrame()
    empty.setObjectName("emptyState")
    empty_layout = QVBoxLayout(empty)
    empty_layout.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.setSpacing(18)
    empty_glyph = QLabel()
    empty_glyph.setPixmap(icon("chart", "#8b949e", 56).pixmap(56, 56))
    empty_glyph.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.addWidget(empty_glyph)
    empty_title = label("选择数据，开始分析", "emptyTitle")
    empty_title.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.addWidget(empty_title)
    empty_description = label("可以先加载示例，也可以导入 TXT、CSV、TSV 或 XLSX 文件。", "emptyDescription", True)
    empty_description.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.addWidget(empty_description)
    empty_actions = QHBoxLayout()
    empty_actions.setSpacing(10)
    empty_actions.addStretch()
    empty_actions.addWidget(button("加载公开示例", "file", window.load_example, primary=True))
    empty_actions.addWidget(button("打开数据文件", "folder", window.open_file))
    empty_actions.addStretch()
    empty_layout.addLayout(empty_actions)
    steps = label("导入数据  →  选择拟合区间  →  计算并导出", "muted")
    steps.setAlignment(Qt.AlignmentFlag.AlignCenter)
    empty_layout.addWidget(steps)
    window.content_stack.addWidget(empty)

    window.tabs = QTabWidget()
    window.tabs.setObjectName("analysisTabs")
    window.plots = {}
    window.plot_toolbars = {}
    window.hover_controllers = {}
    for mode, title in [("linear", "转移特性"), ("log", "半对数曲线"), ("fit", "阈值拟合")]:
        page = QWidget()
        page_layout = QVBoxLayout(page)
        page_layout.setContentsMargins(0, 0, 0, 0)
        page_layout.setSpacing(0)
        figure = Figure(figsize=(7, 4.4), dpi=100, facecolor="#0d1117")
        canvas = StableFigureCanvas(figure)
        canvas.setMinimumSize(0, 0)
        toolbar = PlotToolbar(canvas, window)
        page_layout.addWidget(toolbar)
        page_layout.addWidget(canvas, 1)
        window.plots[mode] = (figure, canvas)
        window.plot_toolbars[mode] = toolbar
        window.hover_controllers[mode] = CurveHoverController(canvas, toolbar, root, mode)
        window.tabs.addTab(page, title)
    window.preview = QTableWidget()
    window.preview.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    window.preview.setAlternatingRowColors(True)
    window.preview.setShowGrid(False)
    window.preview.verticalHeader().setDefaultSectionSize(34)
    window.tabs.addTab(window.preview, "数据预览")

    detail_page = QWidget()
    detail_layout = QVBoxLayout(detail_page)
    detail_layout.setContentsMargins(18, 16, 18, 16)
    detail_layout.setSpacing(14)
    detail_layout.addWidget(label("参数明细", "sectionTitle"))
    window.result_table = QTableWidget(6, 2)
    window.result_table.setHorizontalHeaderLabels(["参数", "计算结果"])
    window.result_table.verticalHeader().setVisible(False)
    window.result_table.verticalHeader().setDefaultSectionSize(32)
    window.result_table.verticalHeader().setSectionResizeMode(QHeaderView.ResizeMode.Fixed)
    window.result_table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    window.result_table.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeMode.Stretch)
    window.result_table.setAlternatingRowColors(True)
    window.result_table.setShowGrid(False)
    window.result_table.setMinimumHeight(185)
    window.result_table.setMaximumHeight(245)
    detail_layout.addWidget(window.result_table)
    detail_layout.addWidget(label("计算说明与数据提示", "sectionTitle"))
    window.notes = QTextBrowser()
    window.notes.setOpenExternalLinks(True)
    detail_layout.addWidget(window.notes, 1)
    window.tabs.addTab(detail_page, "分析记录")
    window.content_stack.addWidget(window.tabs)
    content.addWidget(window.content_stack, 1)
    splitter.addWidget(workspace)
    splitter.setStretchFactor(0, 0)
    splitter.setStretchFactor(1, 1)
    splitter.setSizes([320, 1120])
    window.setCentralWidget(root)
    window.statusBar().setSizeGripEnabled(True)
    window.statusBar().showMessage("就绪。原始文件不会被修改，计算在本机完成。")
    status_local = label("●  本地运行", "muted")
    status_local.setContentsMargins(0, 0, 16, 0)
    window.statusBar().addPermanentWidget(status_local)
